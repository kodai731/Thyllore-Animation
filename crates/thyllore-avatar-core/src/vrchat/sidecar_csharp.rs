use std::fmt::Write;

use serde_json::{Map, Value};

use super::sidecar::{AvatarSidecar, SIDECAR_SCHEMA_VERSION};

pub fn sidecar_json_schema() -> Value {
    serde_json::to_value(schemars::schema_for!(AvatarSidecar)).unwrap_or(Value::Null)
}

/// The Unity mirror of the sidecar types, emitted from the JSON schema so the field sets never drift.
pub fn sidecar_csharp() -> String {
    let schema = sidecar_json_schema();
    let defs = schema
        .get("$defs")
        .and_then(Value::as_object)
        .cloned()
        .unwrap_or_default();

    let mut out = String::new();
    out.push_str("// Generated by `cargo run -p thyllore-avatar-core --bin sidecar_csharp`; edit the Rust sidecar types instead.\n");
    out.push_str("#if UNITY_EDITOR\n\nusing System;\nusing System.Collections.Generic;\nusing Newtonsoft.Json;\n\nnamespace Thyllore.Avatar\n{\n");
    let _ = writeln!(
        out,
        "    public static class SidecarSchema\n    {{\n        public const int SupportedVersion = {SIDECAR_SCHEMA_VERSION};\n    }}\n"
    );
    emit_class(&mut out, "AvatarSidecar", &schema, &defs);
    for (name, def) in &defs {
        if is_string_enum(def) {
            continue;
        }
        out.push('\n');
        emit_class(&mut out, name, def, &defs);
    }
    out.push_str("}\n\n#endif\n");
    out
}

fn is_string_enum(def: &Value) -> bool {
    def.get("enum").is_some()
}

fn emit_class(out: &mut String, name: &str, def: &Value, defs: &Map<String, Value>) {
    let _ = writeln!(out, "    [Serializable]\n    public class {name}\n    {{");
    let mut first = true;
    for (field, ty) in class_fields(def, defs) {
        if !first {
            out.push('\n');
        }
        first = false;
        let _ = writeln!(
            out,
            "        [JsonProperty(\"{field}\")]\n        public {ty} {field}{};",
            initializer(&ty)
        );
    }
    out.push_str("    }\n");
}

/// A tagged union becomes one class carrying the tag and every variant's fields as nullable values.
fn class_fields(def: &Value, defs: &Map<String, Value>) -> Vec<(String, String)> {
    if let Some(variants) = def.get("oneOf").and_then(Value::as_array) {
        let mut fields: Vec<(String, String)> = Vec::new();
        for variant in variants {
            for (field, ty) in class_fields(variant, defs) {
                if fields.iter().any(|(existing, _)| *existing == field) {
                    continue;
                }
                let nullable = if field == "model" { ty } else { nullable(&ty) };
                fields.push((field, nullable));
            }
        }
        return fields;
    }
    let required: Vec<&str> = def
        .get("required")
        .and_then(Value::as_array)
        .map(|names| names.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    def.get("properties")
        .and_then(Value::as_object)
        .map(|properties| {
            properties
                .iter()
                .map(|(field, schema)| {
                    let ty = csharp_type(schema, defs);
                    let ty = if required.contains(&field.as_str()) {
                        ty
                    } else {
                        nullable(&ty)
                    };
                    (field.clone(), ty)
                })
                .collect()
        })
        .unwrap_or_default()
}

fn nullable(ty: &str) -> String {
    match ty {
        "float" | "int" | "long" | "bool" => format!("{ty}?"),
        _ => ty.to_string(),
    }
}

fn initializer(ty: &str) -> String {
    if ty.starts_with("List<") || ty.starts_with("Dictionary<") {
        format!(" = new {ty}()")
    } else {
        String::new()
    }
}

fn csharp_type(schema: &Value, defs: &Map<String, Value>) -> String {
    if let Some(reference) = schema.get("$ref").and_then(Value::as_str) {
        let name = reference.rsplit('/').next().unwrap_or(reference);
        return match defs.get(name) {
            Some(def) if is_string_enum(def) => "string".to_string(),
            _ => name.to_string(),
        };
    }
    if let Some(options) = schema.get("anyOf").and_then(Value::as_array) {
        return options
            .iter()
            .find(|option| option.get("type") != Some(&Value::String("null".into())))
            .map(|option| nullable(&csharp_type(option, defs)))
            .unwrap_or_else(|| "object".to_string());
    }
    let (type_name, is_nullable) = match schema.get("type") {
        Some(Value::String(name)) => (name.as_str(), false),
        Some(Value::Array(names)) => (
            names
                .iter()
                .filter_map(Value::as_str)
                .find(|name| *name != "null")
                .unwrap_or("object"),
            true,
        ),
        _ => ("object", false),
    };
    let ty = match type_name {
        "string" => "string".to_string(),
        "boolean" => "bool".to_string(),
        "number" => "float".to_string(),
        "integer" => integer_type(schema).to_string(),
        "array" => array_type(schema, defs),
        "object" => map_type(schema, defs),
        other => other.to_string(),
    };
    if is_nullable {
        nullable(&ty)
    } else {
        ty
    }
}

fn integer_type(schema: &Value) -> &'static str {
    match schema.get("format").and_then(Value::as_str) {
        Some("uint64") | Some("int64") => "long",
        _ => "int",
    }
}

fn array_type(schema: &Value, defs: &Map<String, Value>) -> String {
    let item = schema
        .get("items")
        .map(|items| csharp_type(items, defs))
        .unwrap_or_else(|| "object".to_string());
    let fixed =
        schema.get("minItems").is_some() && schema.get("minItems") == schema.get("maxItems");
    if fixed {
        format!("{item}[]")
    } else {
        format!("List<{item}>")
    }
}

fn map_type(schema: &Value, defs: &Map<String, Value>) -> String {
    match schema.get("additionalProperties") {
        Some(values) => format!("Dictionary<string, {}>", csharp_type(values, defs)),
        None => "object".to_string(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const CHECKED_IN: &str =
        include_str!("../../../../unity/com.thyllore.avatar/Editor/Sidecar.cs");

    #[test]
    fn unity_sidecar_types_match_the_rust_schema() {
        assert_eq!(
            sidecar_csharp(),
            CHECKED_IN,
            "unity/com.thyllore.avatar/Editor/Sidecar.cs is stale: run `cargo run -p thyllore-avatar-core --bin sidecar_csharp`"
        );
    }

    #[test]
    fn tagged_union_carries_every_variant_field_as_nullable() {
        let csharp = sidecar_csharp();
        assert!(csharp.contains("public class SidecarJointForce"));
        assert!(csharp.contains("public string model;"));
        assert!(csharp.contains("public float? stiffness;"));
        assert!(csharp.contains("public float? bending_relaxation;"));
    }

    #[test]
    fn fixed_arrays_maps_and_options_map_to_csharp_shapes() {
        let csharp = sidecar_csharp();
        assert!(csharp.contains("public float[] offset;"));
        assert!(csharp.contains("public float[] tail;"));
        assert!(csharp.contains(
            "public Dictionary<string, string> humanoid = new Dictionary<string, string>();"
        ));
        assert!(csharp
            .contains("public List<SidecarSpringChain> chains = new List<SidecarSpringChain>();"));
        assert!(csharp.contains("public string expression_mesh;"));
        assert!(csharp.contains("public long texture_bytes;"));
    }
}
